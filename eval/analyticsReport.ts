// eval/analyticsReport.ts
// Hits the production /health endpoint and formats a markdown analytics report.
// Usage: npx tsx eval/analyticsReport.ts

const BACKEND_URL = (process.env.APP_URL || 'https://tldr-shield-292798741977.us-central1.run.app').replace(/\/$/, '');

async function main() {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 10_000);
  let res: Response;
  try {
    res = await fetch(`${BACKEND_URL}/health`, { signal: controller.signal });
  } finally {
    clearTimeout(timeout);
  }
  if (!res!.ok) throw new Error(`Health check failed: ${res!.status}`);
  const h: any = await res.json();

  const date = new Date().toISOString().split('T')[0];
  const report = [
    `## TLDR Shield Weekly Analytics — ${date}`,
    '',
    '### Infrastructure',
    `| Metric | Value |`,
    `|--------|-------|`,
    `| Status | ${h.status} |`,
    `| Uptime | ${Math.round((h.uptimeMs || 0) / 3600000)}h |`,
    `| Memory (rss) | ${Math.round((h.memory?.rss || 0) / 1024 / 1024)}MB |`,
    `| L1 Cache entries | ${h.cache?.entries ?? 'N/A'} |`,
    `| L1 Cache hit rate | ${h.cache?.hitRate ?? 'N/A'} |`,
    `| Firestore connected | ${h.sharedCache?.connected ?? 'N/A'} |`,
    `| Gemini scan keys | ${h.geminiScanKeys ?? h.nimKeys ?? 'N/A'} |`,
    '',
    '### Notes',
    '- Deep scan volume and rating distribution require Firestore Admin access (not available in this run).',
    '- Check Firestore Console → shared_cache for cross-user scan counts.',
    '',
    `_Generated by weekly-analytics workflow. Backend: ${BACKEND_URL}_`,
  ].join('\n');

  process.stdout.write(report + '\n');
}

main().catch(e => { console.error(e); process.exit(1); });
